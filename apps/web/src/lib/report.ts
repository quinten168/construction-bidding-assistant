// ────────────────────────────────────────────────────────────────────────────
// Standard Report — assembles every extracted fact about a plan into one
// estimator-ready document, exportable as Markdown, CSV, or PDF. This is the
// "artifact" the workflow produces (the thing the research says to lead with).
// ────────────────────────────────────────────────────────────────────────────

import { PLAN, type Plan } from "./mock-plan";

export type ReportSection = { id: string; title: string; body: string };

// Build the report as an ordered list of markdown sections (drives the
// streaming side-panel + the export). One source of truth for all formats.
export function buildReport(plan: Plan = PLAN): ReportSection[] {
  const fieldsTable = [
    "| Field | Value | Confidence | Source |",
    "|---|---|---|---|",
    ...plan.fields.map((f) => `| ${f.label} | ${f.value}${f.unit ? " " + f.unit : ""} | ${Math.round(f.confidence * 100)}% | p.${f.page} |`),
  ].join("\n");

  const goNoGo = plan.gotchas.filter((g) => g.family === "go_no_go");
  const pricing = plan.gotchas.filter((g) => g.family === "pricing");
  const gotchaBlock = (list: typeof plan.gotchas) =>
    list
      .map((g) => `- **${g.title}** — ${g.explanation}\n  > “${g.evidence}” — *${g.section}, p.${g.page}* (conf ${Math.round(g.confidence * 100)}%)`)
      .join("\n");

  return [
    {
      id: "summary",
      title: "Recommendation",
      body: `**${plan.recommendation === "BID" ? "Bid" : plan.recommendation === "NO_BID" ? "No-Bid" : "Review"}** — confidence **${Math.round(plan.confidence * 100)}%**.\n\n**Why**\n${plan.rationale.map((r) => `- ${r}`).join("\n")}\n\n**Risks to price in**\n${plan.risks.map((r) => `- ${r}`).join("\n")}`,
    },
    {
      id: "identity",
      title: "Project identity",
      body: [
        "| Field | Value |",
        "|---|---|",
        ...plan.identity.map((r) => `| ${r.label} | ${r.value} |`),
        `| Location | ${plan.county} County, ${plan.state} |`,
        `| Archetype | ${plan.archetype} |`,
      ].join("\n"),
    },
    {
      id: "times",
      title: "Contract times & phasing",
      body: plan.contractTimes.map((c) => `- **${c.label}:** ${c.date}${c.note ? ` — ${c.note}` : ""}`).join("\n"),
    },
    { id: "fields", title: "Extracted fields & quantities", body: fieldsTable },
    { id: "gonogo", title: `Go / no-go gotchas (${goNoGo.length})`, body: gotchaBlock(goNoGo) },
    { id: "pricing", title: `Pricing inputs (${pricing.length})`, body: gotchaBlock(pricing) },
    {
      id: "method",
      title: "Provenance & method",
      body: `Every figure above is extracted from the plan set and pinned to its source page. Quantities are read from the bid schedule (the authoritative table), not from prose references. Gotchas are quoted verbatim and de-duplicated against a 20-type taxonomy.\n\n*Generated by BidIntel · decision support, not final pricing.*`,
    },
  ];
}

// ── Markdown export ──
export function reportMarkdown(plan: Plan = PLAN): string {
  const date = "2026-06-18";
  const head = `# BidIntel Standard Report\n## ${plan.title}\n*${plan.county} County, ${plan.state} · generated ${date}*\n`;
  const body = buildReport(plan)
    .map((s) => `\n---\n\n## ${s.title}\n\n${s.body}`)
    .join("\n");
  return head + body + "\n";
}

// ── CSV export (long format: one row per extracted item) ──
export function reportCSV(plan: Plan = PLAN): string {
  const esc = (v: string | number) => `"${String(v).replace(/"/g, '""')}"`;
  const rows: (string | number)[][] = [["category", "item", "value", "confidence", "page", "evidence"]];
  plan.fields.forEach((f) =>
    rows.push(["field", f.label, `${f.value}${f.unit ? " " + f.unit : ""}`, f.confidence, f.page, ""]),
  );
  plan.gotchas.forEach((g) =>
    rows.push([g.family === "go_no_go" ? "gotcha:go_no_go" : "gotcha:pricing", g.title, g.flag_type, g.confidence, g.page, g.evidence]),
  );
  return rows.map((r) => r.map(esc).join(",")).join("\n");
}

// ── Download helpers (real Blob downloads) ──
export function downloadText(filename: string, content: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

// PDF export via a print-optimized window (real "Save as PDF" through the browser).
export function downloadPDF(plan: Plan = PLAN) {
  const md = reportMarkdown(plan);
  // Minimal markdown → HTML for the print sheet (headings, bold, lists, quotes, tables, rules).
  const html = mdToPrintHtml(md, plan);
  const w = window.open("", "_blank", "width=820,height=1000");
  if (!w) return;
  w.document.write(html);
  w.document.close();
  w.focus();
  setTimeout(() => w.print(), 350);
}

function mdToPrintHtml(_md: string, plan: Plan): string {
  const sections = buildReport(plan);
  const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const inline = (s: string) =>
    esc(s).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>").replace(/\*(.+?)\*/g, "<em>$1</em>").replace(/“|”/g, '"');

  const renderBody = (body: string) => {
    const lines = body.split("\n");
    let out = "";
    let inTable = false;
    for (const line of lines) {
      if (line.startsWith("| ")) {
        if (line.includes("---")) continue;
        const cells = line.split("|").filter((c) => c.trim()).map((c) => `<td>${inline(c.trim())}</td>`).join("");
        if (!inTable) { out += "<table>"; inTable = true; }
        out += `<tr>${cells}</tr>`;
        continue;
      }
      if (inTable) { out += "</table>"; inTable = false; }
      if (line.startsWith("> ")) out += `<blockquote>${inline(line.slice(2))}</blockquote>`;
      else if (line.startsWith("- ")) out += `<li>${inline(line.slice(2))}</li>`;
      else if (line.trim()) out += `<p>${inline(line)}</p>`;
    }
    if (inTable) out += "</table>";
    return out;
  };

  const secHtml = sections.map((s) => `<h2>${esc(s.title)}</h2>${renderBody(s.body)}`).join("<hr/>");

  return `<!doctype html><html><head><meta charset="utf-8"><title>BidIntel Report — ${esc(plan.title)}</title>
  <style>
    @page { margin: 22mm; }
    * { box-sizing: border-box; }
    body { font: 13px/1.55 -apple-system, Inter, Arial, sans-serif; color: #2a2520; max-width: 720px; margin: 0 auto; padding: 24px; }
    h1 { font-size: 24px; margin: 0 0 2px; }
    .sub { color: #8a7f72; font-size: 12px; margin-bottom: 18px; }
    h2 { font-size: 15px; margin: 20px 0 6px; color: #b35b3e; }
    hr { border: none; border-top: 1px solid #eadfce; margin: 14px 0; }
    p { margin: 6px 0; } li { margin: 3px 0 3px 18px; }
    blockquote { margin: 4px 0; padding: 4px 10px; border-left: 3px solid #d9a78f; color: #6c6258; font-style: italic; font-size: 12px; }
    table { border-collapse: collapse; width: 100%; margin: 8px 0; font-size: 12px; }
    td { border: 1px solid #eadfce; padding: 5px 8px; }
    tr:first-child td { background: #f6f0e6; font-weight: 600; }
    .brand { display:flex; align-items:center; gap:8px; }
    .dot { width:14px; height:14px; border-radius:50%; background:#d9774f; display:inline-block; }
  </style></head>
  <body>
    <div class="brand"><span class="dot"></span><strong>BidIntel</strong> Standard Report</div>
    <h1>${esc(plan.title)}</h1>
    <div class="sub">${esc(plan.county)} County, ${esc(plan.state)} · generated 2026-06-18 · decision support, not final pricing</div>
    ${secHtml}
  </body></html>`;
}
