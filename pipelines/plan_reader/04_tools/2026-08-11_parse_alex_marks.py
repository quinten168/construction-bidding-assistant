#!/usr/bin/env python3
"""
2026-08-11_parse_alex_marks.py — read Alex's marks out of the returned .docx, from the XML.

READ-ONLY. Parses
    05_knowledge/_markup/2026-08-03_ALEX RESPONSES_material_mapping_for_CSI_v3.docx

The form was generated by 14_build_material_preread_v2.py, whose checkboxes are w:sdt content
controls built in 13_render_preread_docx.add_checkbox: the STATE lives in
`<w14:checkbox><w14:checked w14:val="..."/>`, NOT in the rendered glyph inside <w:sdtContent>.
Word rewrites the glyph when a box is clicked, but the glyph is also whatever the generator wrote,
so the attribute is the only trustworthy source. Both are reported here so they can be cross-checked.

Standing rule — a failure and a legitimate empty answer must not share a return value. Three
distinct states are emitted and never collapsed:
    CHECKED     w14:checked w14:val in {1, true, on}
    UNCHECKED   w14:checked present, w14:val in {0, false, off}
    ABSENT      no w14:checkbox / no w14:checked element at all  -> a structural problem, not a "no"
A fourth, MALFORMED, covers a w14:val this parser does not recognise.

Output: JSON on stdout (or --out), one record per table row that carries checkboxes, with the row's
other cell text so a mark can be tied to the material it sits next to. Also dumps every non-empty
free-text cell (the typed "Move to ___" answers and the write-in tables).

Run:
    python3 pipelines/plan_reader/04_tools/2026-08-11_parse_alex_marks.py --out /tmp/alex.json
"""
import argparse
import json
import re
import sys
import zipfile

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
W14 = "{http://schemas.microsoft.com/office/word/2010/wordml}"

DOCX = ("pipelines/plan_reader/05_knowledge/_markup/"
        "2026-08-03_ALEX RESPONSES_material_mapping_for_CSI_v3.docx")

TRUE = {"1", "true", "on"}
FALSE = {"0", "false", "off"}


def checkbox_state(sdt):
    """(state, raw_val, glyph). Never returns UNCHECKED for a structurally missing control."""
    glyph = "".join(t.text or "" for t in sdt.iter(W + "t"))
    box = sdt.find(f"./{W}sdtPr/{W14}checkbox")
    if box is None:
        return "ABSENT_NO_CHECKBOX_ELEMENT", None, glyph
    checked = box.find(f"./{W14}checked")
    if checked is None:
        return "ABSENT_NO_CHECKED_ELEMENT", None, glyph
    val = checked.get(W14 + "val")
    if val is None:
        # w14:checked with no val attribute means checked, per the schema default; flag it anyway.
        return "CHECKED_IMPLICIT_NO_VAL", None, glyph
    if val in TRUE:
        return "CHECKED", val, glyph
    if val in FALSE:
        return "UNCHECKED", val, glyph
    return "MALFORMED_VAL", val, glyph


def para_items(p):
    """Walk a paragraph's direct children in document order, pairing each checkbox with the run
    text that follows it — that is exactly how checkbox_line() in 13_render_preread_docx.py lays
    labels out (add_checkbox, then a ' ' + label run)."""
    items = []
    for child in p:
        if child.tag == W + "sdt":
            state, val, glyph = checkbox_state(child)
            items.append({"kind": "checkbox", "state": state, "w14_val": val, "glyph": glyph,
                          "label": ""})
        elif child.tag == W + "r":
            txt = "".join(t.text or "" for t in child.iter(W + "t"))
            if not txt:
                continue
            if items and items[-1]["kind"] == "checkbox":
                items[-1]["label"] += txt
            else:
                items.append({"kind": "text", "text": txt})
        elif child.tag in (W + "ins", W + "del"):
            txt = "".join(t.text or "" for t in child.iter(W + "t"))
            items.append({"kind": "tracked_change", "tag": child.tag.split("}")[1], "text": txt})
    return items


def cell_parse(tc):
    items = []
    for p in tc.findall(f"./{W}p"):
        items.extend(para_items(p))
    text = "".join(i.get("text", "") for i in items if i["kind"] == "text").strip()
    boxes = [i for i in items if i["kind"] == "checkbox"]
    for b in boxes:
        b["label"] = re.sub(r"\s+", " ", b["label"]).strip()
    return text, boxes, [i for i in items if i["kind"] == "tracked_change"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--docx", default=DOCX)
    ap.add_argument("--out")
    args = ap.parse_args()

    import xml.etree.ElementTree as ET
    with zipfile.ZipFile(args.docx) as z:
        names = z.namelist()
        root = ET.fromstring(z.read("word/document.xml"))
        comments = [n for n in names if "comment" in n.lower()]

    body = root.find(f"./{W}body")
    rows, loose_paras, tracked = [], [], []
    table_i = 0
    for el in body:
        if el.tag == W + "tbl":
            table_i += 1
            for r_i, tr in enumerate(el.findall(f"./{W}tr")):
                cells = []
                for tc in tr.findall(f"./{W}tc"):
                    text, boxes, tc_tracked = cell_parse(tc)
                    tracked.extend(tc_tracked)
                    cells.append({"text": text, "checkboxes": boxes})
                if any(c["checkboxes"] for c in cells) or any(c["text"] for c in cells):
                    rows.append({"table": table_i, "row": r_i, "cells": cells})
        elif el.tag == W + "p":
            items = para_items(el)
            tracked.extend(i for i in items if i["kind"] == "tracked_change")
            if any(i["kind"] == "checkbox" for i in items) or "".join(
                    i.get("text", "") for i in items).strip():
                loose_paras.append(items)

    all_boxes = [b for r in rows for c in r["cells"] for b in c["checkboxes"]]
    all_boxes += [i for p in loose_paras for i in p if i["kind"] == "checkbox"]
    summary = {}
    for b in all_boxes:
        summary[b["state"]] = summary.get(b["state"], 0) + 1

    out = {
        "docx": args.docx,
        "comment_parts_in_zip": comments,
        "tracked_changes": tracked,
        "checkbox_state_counts": summary,
        "total_checkboxes": len(all_boxes),
        "rows": rows,
        "loose_paragraphs": loose_paras,
    }
    text = json.dumps(out, indent=1, ensure_ascii=False)
    if args.out:
        open(args.out, "w", encoding="utf-8").write(text)
        print(json.dumps({"checkbox_state_counts": summary, "total": len(all_boxes),
                          "comment_parts": comments, "tracked_changes": len(tracked)}, indent=1))
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
